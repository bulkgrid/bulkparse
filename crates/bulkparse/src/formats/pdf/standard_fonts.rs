//! Standard Latin PDF font metrics.
//! Adobe Core 14 AFM widths; see THIRD_PARTY_NOTICES.md for attribution.
//! Exact names only: similarly named custom fonts are not metric-compatible.
pub(super) fn width(name: &[u8], text: &str) -> Option<f64> {
    let table = match name {
        b"Courier" => COURIER,
        b"Courier-Bold" => COURIER_BOLD,
        b"Courier-Oblique" => COURIER_OBLIQUE,
        b"Courier-BoldOblique" => COURIER_BOLDOBLIQUE,
        b"Helvetica" => HELVETICA,
        b"Helvetica-Bold" => HELVETICA_BOLD,
        b"Helvetica-Oblique" => HELVETICA_OBLIQUE,
        b"Helvetica-BoldOblique" => HELVETICA_BOLDOBLIQUE,
        b"Times-Roman" => TIMES_ROMAN,
        b"Times-Bold" => TIMES_BOLD,
        b"Times-Italic" => TIMES_ITALIC,
        b"Times-BoldItalic" => TIMES_BOLDITALIC,
        _ => return None,
    };
    let mut chars = text.chars();
    let c = match chars.next()? {
        '\u{00a0}' => ' ',
        '\u{00ad}' => '-',
        c => c,
    };
    if chars.next().is_some() {
        return None;
    }
    table
        .binary_search_by_key(&c, |&(ch, _)| ch)
        .ok()
        .map(|i| f64::from(table[i].1))
}

