#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Limits {
    /// Total retained image bytes, separate from decoded text.
    pub max_image_bytes: usize,
    pub max_images: usize,
    pub max_input_bytes: usize,
    pub max_text_bytes: usize,
    pub max_nodes: usize,
    pub max_depth: usize,
    pub max_table_cells: usize,
    /// Additional populated cells generated by compact row/column repetition.
    /// Separate from actual source cells so tiny ODF inputs cannot request a
    /// multi-million-cell model merely because large ordinary sheets fit.
    pub max_cell_repetitions: usize,
    pub max_pages: usize,
    pub max_archive_entries: usize,
    pub max_expanded_bytes: usize,
    /// Native Markdown writer output ceiling, including markup and empty cells.
    /// Structured/string-rendering APIs do not use this writer-specific bound.
    pub max_markdown_bytes: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            max_image_bytes: 64 * 1024 * 1024,
            max_images: 1_000,
            max_input_bytes: 32 * 1024 * 1024,
            max_text_bytes: 32 * 1024 * 1024,
            max_nodes: 16 * 1024 * 1024,
            max_depth: 64,
            max_table_cells: 4 * 1024 * 1024,
            max_cell_repetitions: 100_000,
            max_pages: 2_000,
            max_archive_entries: 10_000,
            max_expanded_bytes: 256 * 1024 * 1024,
            max_markdown_bytes: 128 * 1024 * 1024,
        }
    }
}

impl Limits {
    /// Compatibility alias: these budgets are now the default. No retry or
    /// document-specific routing is required to process large spreadsheets.
    pub fn large_spreadsheets() -> Self {
        Self::default()
    }

    /// Earlier conservative total-work budgets for callers that prefer early
    /// rejection. Explicit caller limits are always honored, never escalated.
    pub fn conservative() -> Self {
        Self {
            max_nodes: 200_000,
            max_table_cells: 100_000,
            max_expanded_bytes: 64 * 1024 * 1024,
            ..Self::default()
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
