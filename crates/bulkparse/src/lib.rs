#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Options {
    /// Retain supported Office/EPUB image files in document.assets. PDFs do not export images.
    pub extract_images: bool,
    /// File-to-Markdown API only: save Office/EPUB assets without rewriting Markdown.
    pub export_images: bool,
    pub format: Option<Format>,
    pub strict: bool,
    pub csv_has_headers: bool,
    /// None detects comma, semicolon, tab or pipe from bounded complete records.
    pub csv_delimiter: Option<char>,
    /// None detects a Unicode BOM, then UTF-8, with a diagnosed Windows-1252
    /// fallback for legacy CSV exports. Set Utf8 to require strict UTF-8.
    pub csv_encoding: Option<TextEncoding>,
    /// Opt in to bounded, explicitly partial spreadsheet/CSV recovery after a
    /// resource limit. Strict mode never returns this reduced-fidelity output.
    pub partial_on_limit: bool,
    /// Expand PDF presentation forms/ligatures and turn zero-width word breaks
    /// into spaces. Enabled by default; set false for raw mapped forms.
    /// ActualText with visible content is preserved, including shaping controls.
    pub pdf_normalize_unicode: bool,
    /// With a provider, retry all pages through OCR while retaining native text on failure.
    pub pdf_force_ocr: bool,
    pub limits: Limits,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            extract_images: true,
            export_images: false,
            format: None,
            strict: false,
            csv_has_headers: false,
            csv_delimiter: None,
            csv_encoding: None,
            partial_on_limit: false,
            pdf_normalize_unicode: true,
            pdf_force_ocr: false,
            limits: Limits::default(),
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct CancellationToken(Arc<AtomicBool>);
impl CancellationToken {
    pub fn cancel(&self) {
        self.0.store(true, Ordering::Relaxed);
    }
    pub fn is_cancelled(&self) -> bool {
        self.0.load(Ordering::Relaxed)
    }
}

#[derive(Debug, Clone, Default)]
pub struct Parser {
    pub options: Options,
}
impl Parser {
    pub fn new(options: Options) -> Self {
        Self { options }
    }
    pub fn parse_bytes(&self, bytes: &[u8], filename: Option<&str>) -> Result<ParseResult, Error> {
        self.parse_with_cancel(bytes, filename, &CancellationToken::default())
    }
    pub fn parse_with_cancel(
        &self,
        bytes: &[u8],
        filename: Option<&str>,
        cancel: &CancellationToken,
    ) -> Result<ParseResult, Error> {
        self.parse_internal(bytes, filename, cancel, None)
    }
    /// Inspect native PDF evidence without layout reconstruction or OCR.
    /// Uses the same classifier and resource limits as conversion.
    pub fn inspect_pdf(&self, bytes: &[u8]) -> Result<PdfInspection, Error> {
        self.inspect_pdf_with_cancel(bytes, &CancellationToken::default())
    }
    pub fn inspect_pdf_with_cancel(
        &self,
        bytes: &[u8],
        cancel: &CancellationToken,
    ) -> Result<PdfInspection, Error> {
        if bytes.len() > self.options.limits.max_input_bytes {
            return Err(Error::Limit("max_input_bytes"));
        }
        let mut ctx = Context::new(&self.options, cancel);
        ctx.check()?;
        #[cfg(feature = "pdf")]
        {
            formats::pdf::inspect(bytes, &mut ctx)
        }
        #[cfg(not(feature = "pdf"))]
        {
            let _ = &mut ctx;
            Err(Error::Unsupported("PDF support is disabled".into()))
        }
    }
    /// OCR is opt-in. The shared PDF inspector selects image-only pages,
    /// suspect text layers, sparse text over large images and textless vectors.
    /// Whole-page OCR replaces native text only when usable OCR is returned.
    pub fn parse_with_pdf_ocr(
        &self,
        bytes: &[u8],
        filename: Option<&str>,
        cancel: &CancellationToken,
        provider: &dyn PdfOcrProvider,
        budget: PdfOcrBudget,
    ) -> Result<ParseResult, Error> {
        self.parse_internal(bytes, filename, cancel, Some((provider, budget)))
    }
    fn parse_internal(
        &self,
        bytes: &[u8],
        filename: Option<&str>,
        cancel: &CancellationToken,
        ocr: Option<(&dyn PdfOcrProvider, PdfOcrBudget)>,
    ) -> Result<ParseResult, Error> {
        if bytes.len() > self.options.limits.max_input_bytes {
            return Err(Error::Limit("max_input_bytes"));
        }
        let mut ctx = Context::new(&self.options, cancel);
        ctx.ocr = ocr;
        ctx.check()?;
        let format = formats::detect(bytes, filename, self.options.format, &mut ctx)?;
        assets::prepare(format, bytes, &mut ctx)?;
        let blocks = match formats::parse(format, bytes, &mut ctx) {
            Ok(blocks) => blocks,
            Err(Error::Limit(limit))
                if self.options.partial_on_limit
                    && !self.options.strict
                    && matches!(
                        format,
                        Format::Csv | Format::Tsv | Format::Xls | Format::Xlsx | Format::Ods
                    )
                    && matches!(
                        limit,
                        "max_nodes" | "max_table_cells" | "max_text_bytes" | "max_expanded_bytes"
                    ) =>
            {
                // The failed attempt has dropped its intermediate allocations.
                // Recovery gets the same caps, never an increased budget.
                ctx = Context::new(&self.options, cancel);
                ctx.recovering_limits = true;
                assets::prepare(format, bytes, &mut ctx)?;
                let blocks = formats::recover(format, bytes, &mut ctx)?;
                ctx.diagnostic("resource_limit_partial",
                    &format!("Normal conversion exceeded {limit}. Bounded recovery returned a partial prefix; omitted content and unexamined tails are not validated. Limits were not increased."),
                    Source::default(), true);
                blocks
            }
            Err(e) => return Err(e),
        };
        assets::collect(format, bytes, &mut ctx)?;
        ctx.check()?;
        let status = if ctx.diagnostics.iter().any(|d| d.content_loss) {
            Status::Partial
        } else {
            Status::Complete
        };
        if self.options.strict && status == Status::Partial {
            return Err(Error::Incomplete(ctx.diagnostics.len()));
        }
        Ok(ParseResult {
            pdf_inspection: ctx.pdf_inspection,
            document: Document {
                schema_version: SCHEMA_VERSION.into(),
                format,
                blocks,
                assets: ctx.assets,
            },
            status,
            diagnostics: ctx.diagnostics,
            coverage: ctx.coverage,
            parser_version: env!("CARGO_PKG_VERSION").into(),
        })
    }
    /// Capped input read; the parser may need random access after this step.
    pub fn parse_reader(
        &self,
        reader: impl Read,
        filename: Option<&str>,
    ) -> Result<ParseResult, Error> {
        let mut bytes = Vec::new();
        reader
            .take((self.options.limits.max_input_bytes as u64).saturating_add(1))
            .read_to_end(&mut bytes)?;
        self.parse_bytes(&bytes, filename)
    }
    #[cfg(not(target_arch = "wasm32"))]
    pub fn parse_file(&self, path: impl AsRef<std::path::Path>) -> Result<ParseResult, Error> {
        let path = path.as_ref();
        self.parse_reader(
            std::fs::File::open(path)?,
            path.file_name().and_then(|s| s.to_str()),
        )
    }
}

