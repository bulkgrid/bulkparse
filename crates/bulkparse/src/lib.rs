pub fn json_schema() -> serde_json::Value {
    serde_json::to_value(schemars::schema_for!(ParseResult)).expect("schema serialization")
}

/// One transport contract for native bindings and WASM. Parse exactly once.
#[derive(Debug, Serialize)]
pub struct Conversion {
    #[serde(flatten)]
    pub result: ParseResult,
    pub markdown: String,
    pub render_diagnostics: Vec<Diagnostic>,
}

// Avoid serde's flatten buffer, which otherwise holds a second generic copy of
// the complete document while decoding process-host replies.
impl<'de> Deserialize<'de> for Conversion {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        #[derive(Deserialize)]
        struct Wire {
            pdf_inspection: Option<PdfInspection>,
            document: Document,
            status: Status,
            diagnostics: Vec<Diagnostic>,
            coverage: Vec<Coverage>,
            parser_version: String,
            markdown: String,
            render_diagnostics: Vec<Diagnostic>,
        }
        let w = Wire::deserialize(d)?;
        Ok(Self {
            result: ParseResult {
                pdf_inspection: w.pdf_inspection,
                document: w.document,
                status: w.status,
                diagnostics: w.diagnostics,
                coverage: w.coverage,
                parser_version: w.parser_version,
            },
            markdown: w.markdown,
            render_diagnostics: w.render_diagnostics,
        })
    }
}

pub fn parse(bytes: &[u8], filename: Option<&str>, options: Options) -> Result<Conversion, Error> {
    let strict = options.strict;
    let result = Parser::new(options).parse_bytes(bytes, filename)?;
    let rendered = result.to_markdown();
    if strict && rendered.diagnostics.iter().any(|d| d.content_loss) {
        return Err(Error::Incomplete(rendered.diagnostics.len()));
    }
    Ok(Conversion {
        result,
        markdown: rendered.text,
        render_diagnostics: rendered.diagnostics,
    })
}

/// Shared JSON bridge; adapters only move bytes and release host runtimes.
pub fn parse_json(
    bytes: &[u8],
    filename: Option<&str>,
    options_json: Option<&str>,
) -> Result<String, Error> {
    let options = options_json
        .map(serde_json::from_str::<Options>)
        .transpose()
        .map_err(|e| Error::Malformed(format!("invalid options: {e}")))?
        .unwrap_or_default();
    serde_json::to_string(&parse(bytes, filename, options)?)
        .map_err(|e| Error::Malformed(e.to_string()))
}

/// Inspection-only JSON transport shared by all bindings.
pub fn inspect_pdf_json(bytes: &[u8], options_json: Option<&str>) -> Result<String, Error> {
    let options = options_json
        .map(serde_json::from_str::<Options>)
        .transpose()
        .map_err(|e| Error::Malformed(format!("invalid options: {e}")))?
        .unwrap_or_default();
    serde_json::to_string(&Parser::new(options).inspect_pdf(bytes)?)
        .map_err(|e| Error::Malformed(e.to_string()))
}

pub fn error_json(error: &Error) -> String {
    serde_json::json!({"code": error.code(), "message": error.to_string()}).to_string()
}

