#[cfg(all(test, feature = "office"))]
mod accounting_tests {
    use super::*;

    #[test]
    fn batched_accounting_preserves_limits_cancellation_and_counters() {
        for cancelled in [false, true] {
            let cancel = CancellationToken::default();
            if cancelled {
                cancel.cancel();
            }
            for node_limit in [0, 1, 3, 8, usize::MAX] {
                for cell_limit in [0, 1, 3, 8, usize::MAX] {
                    let mut options = Options::default();
                    options.limits.max_nodes = node_limit;
                    options.limits.max_table_cells = cell_limit;
                    for initial in [0, 1, 4, usize::MAX] {
                        for count in 0..12 {
                            for cells in [false, true] {
                                let mut sequential = Context::new(&options, &cancel);
                                sequential.nodes = initial;
                                sequential.table_cells = initial;
                                let mut batched = sequential.budget_probe();
                                let expected = (0..count).try_for_each(|_| {
                                    if cells {
                                        sequential.cell()
                                    } else {
                                        sequential.node()
                                    }
                                });
                                let actual = if cells {
                                    batched.account_cells(count)
                                } else {
                                    batched.account_nodes(count)
                                };
                                assert_eq!(
                                    actual.err().map(|e| (e.code(), e.to_string())),
                                    expected.err().map(|e| (e.code(), e.to_string()))
                                );
                                assert_eq!(
                                    (batched.nodes, batched.table_cells, batched.next_id),
                                    (sequential.nodes, sequential.table_cells, sequential.next_id)
                                );
                            }
                        }
                    }
                }
            }
        }
    }
}
