pub(crate) struct Context<'a> {
    pub assets: Vec<ImageAsset>,
    image_bytes: usize,
    images_prepared: bool,
    image_index: std::collections::HashMap<String, usize>,
    pub options: &'a Options,
    cancel: &'a CancellationToken,
    ocr: Option<(&'a dyn PdfOcrProvider, PdfOcrBudget)>,
    nodes: usize,
    text_bytes: usize,
    table_cells: usize,
    repeated_cells: usize,
    next_id: usize,
    pub recovering_limits: bool,
    pub diagnostics: Vec<Diagnostic>,
    pub coverage: Vec<Coverage>,
    pub pdf_inspection: Option<PdfInspection>,
}
impl<'a> Context<'a> {
    fn new(options: &'a Options, cancel: &'a CancellationToken) -> Self {
        Self {
            assets: vec![],
            image_bytes: 0,
            images_prepared: false,
            image_index: Default::default(),
            options,
            cancel,
            ocr: None,
            nodes: 0,
            text_bytes: 0,
            table_cells: 0,
            repeated_cells: 0,
            next_id: 0,
            recovering_limits: false,
            diagnostics: vec![],
            coverage: vec![],
            pdf_inspection: None,
        }
    }
    pub fn check(&self) -> Result<(), Error> {
        if self.cancel.is_cancelled() {
            Err(Error::Cancelled)
        } else {
            Ok(())
        }
    }
    /// Independent budget counters for allocation-free planning. Diagnostics and
    /// output IDs remain owned by the actual extraction attempt.
    pub(crate) fn budget_probe(&self) -> Self {
        let mut probe = Self::new(self.options, self.cancel);
        probe.nodes = self.nodes;
        probe.text_bytes = self.text_bytes;
        probe.table_cells = self.table_cells;
        probe.repeated_cells = self.repeated_cells;
        probe
    }
    pub fn fits(&self, nodes: usize, cells: usize, text: usize) -> bool {
        self.nodes.saturating_add(nodes) <= self.options.limits.max_nodes
            && self.table_cells.saturating_add(cells) <= self.options.limits.max_table_cells
            && self.text_bytes.saturating_add(text) <= self.options.limits.max_text_bytes
    }
    pub fn depth(&self, depth: usize) -> Result<(), Error> {
        self.check()?;
        if depth > self.options.limits.max_depth {
            Err(Error::Limit("max_depth"))
        } else {
            Ok(())
        }
    }
    pub fn node(&mut self) -> Result<(), Error> {
        self.check()?;
        self.nodes = self.nodes.saturating_add(1);
        if self.nodes > self.options.limits.max_nodes {
            Err(Error::Limit("max_nodes"))
        } else {
            Ok(())
        }
    }
    pub fn text(&mut self, text: &str) -> Result<(), Error> {
        self.text_bytes = self.text_bytes.saturating_add(text.len());
        if self.text_bytes > self.options.limits.max_text_bytes {
            Err(Error::Limit("max_text_bytes"))
        } else {
            self.check()
        }
    }
    pub fn cell(&mut self) -> Result<(), Error> {
        self.table_cells = self.table_cells.saturating_add(1);
        if self.table_cells > self.options.limits.max_table_cells {
            Err(Error::Limit("max_table_cells"))
        } else {
            self.node()
        }
    }
    /// Charge already-counted XML nodes without walking the count a second
    /// time. The failure path preserves the original error/counter ordering.
    #[cfg(feature = "office")]
    pub(crate) fn account_nodes(&mut self, count: usize) -> Result<(), Error> {
        if count == 0 {
            return Ok(());
        }
        if self.fits(count, 0, 0) {
            self.node()?;
            self.nodes = self.nodes.saturating_add(count - 1);
            self.check()
        } else {
            for _ in 0..count {
                self.node()?;
            }
            Ok(())
        }
    }
    /// Preflight a known grid size. Actual cell construction still validates
    /// its content; this only batches accounting when both budgets fit.
    #[cfg(feature = "office")]
    pub(crate) fn account_cells(&mut self, count: usize) -> Result<(), Error> {
        if count == 0 {
            return Ok(());
        }
        if self.fits(count, count, 0) {
            self.cell()?;
            self.table_cells = self.table_cells.saturating_add(count - 1);
            self.nodes = self.nodes.saturating_add(count - 1);
            self.check()
        } else {
            for _ in 0..count {
                self.cell()?;
            }
            Ok(())
        }
    }
    #[cfg(feature = "office")]
    pub(crate) fn repeat_cells(&mut self, extra: usize) -> Result<(), Error> {
        self.check()?;
        self.repeated_cells = self.repeated_cells.saturating_add(extra);
        if self.repeated_cells > self.options.limits.max_cell_repetitions {
            Err(Error::Limit("max_cell_repetitions"))
        } else {
            Ok(())
        }
    }
    pub fn block(&mut self, content: BlockContent, source: Source) -> Result<Block, Error> {
        let id = self.reserve_block()?;
        Ok(Block {
            id: block_id(id),
            content,
            source,
        })
    }
    /// Charge a block now, materializing it only when its output row is needed.
    pub(crate) fn reserve_block(&mut self) -> Result<usize, Error> {
        self.node()?;
        self.next_id += 1;
        Ok(self.next_id)
    }
    pub fn diagnostic(&mut self, code: &str, message: &str, source: Source, content_loss: bool) {
        // Deduplicate repeated page/part warnings without unbounded diagnostic growth.
        if !self
            .diagnostics
            .iter()
            .any(|d| d.code == code && d.source == source)
        {
            self.diagnostics
                .push(Diagnostic::new(code, message, source, content_loss));
        }
    }
}

// Construct the stable decimal ID in one exact-size allocation. Formatting a
// short prefix plus an unknown-width integer can grow the String per block.
pub(crate) fn block_id(id: usize) -> String {
    let mut buffer = itoa::Buffer::new();
    let digits = buffer.format(id);
    let mut output = String::with_capacity(1 + digits.len());
    output.push('b');
    output.push_str(digits);
    output
}

