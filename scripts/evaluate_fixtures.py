#!/usr/bin/env python3
"""Offline evaluation against existing reference checkouts; never copies inputs.

Runs two CLI conversions per accepted file (JSON and Markdown). Reference output
is read from committed snapshots, not regenerated by running competitors.
POSIX only: per-process CPU/file limits plus a wall-time watchdog. Peak RSS is
measured by wait4; Linux additionally applies an address-space limit.
"""
from __future__ import annotations
from bulkparse_cli import parse_command

import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import html
import json
import os
from pathlib import Path
import platform
import re
import resource
import signal
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
FORMATS = {'.txt': 'text', '.md': 'markdown', '.csv': 'csv', '.tsv': 'tsv',
           '.ipynb': 'notebook', '.docx': 'docx', '.docm': 'docx', '.pdf': 'pdf'}
PRIMARY = {'docx', 'pdf', 'ocr', 'csv', 'md', 'md_deepseek'}
RAGGED = {'csv-too-many-columns.csv', 'csv-too-few-columns.csv', 'csv-inconsistent-header.csv'}


def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def source_digest():
    h = hashlib.sha256()
    files = [ROOT / 'Cargo.toml', ROOT / 'Cargo.lock']
    files += sorted((ROOT / 'crates').rglob('*.rs'))
    files += sorted((ROOT / 'crates').rglob('Cargo.toml'))
    for p in files:
        h.update(str(p.relative_to(ROOT)).encode() + b'\0' + p.read_bytes() + b'\0')
    return h.hexdigest()


def inventory(anydoc, docling):
    records = []
    for project, checkout, sub in [('anydoc', anydoc, 'tests/fixtures'), ('docling', docling, 'tests/data')]:
        base = checkout / sub
        if not base.is_dir():
            raise ValueError(f'Missing input directory: {base}')
        for p in sorted(base.rglob('*')):
            if not p.is_file() or p.is_symlink() or p.suffix.lower() not in FORMATS:
                continue
            rel = p.relative_to(base)
            if project == 'docling' and 'sources' not in rel.parts:
                continue
            if project == 'anydoc':
                group = {'abuse': 'resource_abuse', 'malformed': 'malformed'}.get(rel.parts[0], 'quality')
                ref = checkout / 'tests/snapshots' / ('snapshots__' + str(rel).replace('/', '__') + '.snap')
                kind = 'insta_snapshot'
            else:
                group = ('encrypted' if rel.parts[0] == 'pdf_password' and p.suffix == '.pdf'
                         else 'malformed' if rel.parts[0] == 'csv' and p.name in RAGGED
                         else 'quality' if rel.parts[0] in PRIMARY else 'supplemental')
                index = rel.parts.index('sources')
                reference_base = base.joinpath(*rel.parts[:index], 'groundtruth', *rel.parts[index + 1:-1])
                choices = [reference_base / (p.name + '.md'), reference_base / (p.stem + '.md')]
                ref = next((x for x in choices if x.is_file()), None)
                kind = 'docling_markdown'
            if ref is not None and not ref.is_file():
                ref = None
            records.append({
                'id': f'{project}/{rel.as_posix()}', 'project': project, 'group': group,
                'format': FORMATS[p.suffix.lower()], 'source_path': str(p),
                'source_relative': p.relative_to(checkout).as_posix(),
                'source_bytes': p.stat().st_size, 'source_sha256': sha(p),
                'upstream_url': f'https://github.com/{"firecrawl/anydoc" if project == "anydoc" else "docling-project/docling"}/blob/main/{p.relative_to(checkout).as_posix()}',
                'revision': None, 'revision_note': 'Downloaded checkout has no verified Git revision; file hashes identify these bytes.',
                'reference_path': str(ref) if ref else None,
                'reference_sha256': sha(ref) if ref else None, 'reference_kind': kind if ref else None,
                'redistribution': 'not reviewed; original inputs and converted text are excluded from shared reports',
            })
    return records


def reference(record):
    if not record['reference_path']:
        return None
    text = Path(record['reference_path']).read_text(encoding='utf-8')
    if record['reference_kind'] == 'insta_snapshot':
        text = text.split('\n---\n', 1)[1]
    return text


def tokens(text):
    # A deliberately simple diagnostic, not a Markdown renderer or quality score.
    text = re.sub(r'!?\[([^\]]*)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'<[^>]*>', ' ', text)
    return Counter(re.findall(r'\w+', html.unescape(text).casefold()))


def compare(actual, expected):
    if expected.lstrip().startswith(('ERROR:', 'PANIC')):
        return {'reference_is_error': True}
    a, b = tokens(actual), tokens(expected)
    common = sum((a & b).values())
    norm = lambda s: '\n'.join(x.rstrip() for x in s.replace('\r\n', '\n').strip().splitlines())
    return {'reference_is_error': False, 'normalized_exact': norm(actual) == norm(expected),
            'reference_tokens': sum(b.values()), 'output_tokens': sum(a.values()),
            'token_recall_proxy': common / sum(b.values()) if b else None,
            'token_precision_proxy': common / sum(a.values()) if a else None}


def count_model(value):
    counts = Counter()
    def visit(v):
        if isinstance(v, dict):
            if 'type' in v:
                counts[v['type']] += 1
            for x in v.values(): visit(x)
        elif isinstance(v, list):
            for x in v: visit(x)
    visit(value)
    return dict(counts)


def run_cli(binary, source, output, args):
    stdout, stderr = output.with_suffix('.stdout'), output.with_suffix('.stderr')
    def limits():
        resource.setrlimit(resource.RLIMIT_CPU, (args.cpu_seconds, args.cpu_seconds + 1))
        resource.setrlimit(resource.RLIMIT_FSIZE, (args.output_mib * 1024**2,) * 2)
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
        if platform.system() == 'Linux':
            resource.setrlimit(resource.RLIMIT_AS, (args.rss_mib * 1024**2,) * 2)
    started = time.monotonic()
    reason, usage = None, None
    with stdout.open('wb') as out, stderr.open('wb') as err:
        process = subprocess.Popen([str(binary), parse_command(binary), str(source), '--to', output.name],
                                   stdin=subprocess.DEVNULL, stdout=out, stderr=err,
                                   start_new_session=True, preexec_fn=limits)
        try:
            while True:
                pid, status, observed = os.wait4(process.pid, os.WNOHANG)
                if pid:
                    usage = observed
                    code = os.waitstatus_to_exitcode(status)
                    process.returncode = code
                    break
                if time.monotonic() - started > args.timeout:
                    reason = 'wall_timeout'
                    try: os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError: pass
                time.sleep(0.02)
        finally:
            if process.returncode is None:
                process.kill()
                process.wait()
    if code == -signal.SIGXCPU: reason = 'cpu_limit'
    if code == -signal.SIGXFSZ: reason = 'output_limit'
    return {'exit_code': code, 'harness_stop': reason,
            'wall_ms_including_watchdog': round((time.monotonic() - started) * 1000, 2),
            'peak_rss_kib': round(usage.ru_maxrss / (1024 if platform.system() == 'Darwin' else 1), 2),
            'cpu_seconds': round(usage.ru_utime + usage.ru_stime, 4),
            'stdout_path': str(stdout), 'stderr_path': str(stderr)}


def error(stderr):
    for line in reversed(stderr.splitlines()):
        try:
            obj = json.loads(line)
            if isinstance(obj, dict) and 'code' in obj: return obj
        except ValueError: pass
    return None


def evaluate(record, binary, artifacts, args):
    case = artifacts / record['id']
    case.mkdir(parents=True)
    result = {k: record[k] for k in ['id', 'project', 'group', 'format', 'source_sha256']}
    run = run_cli(binary, Path(record['source_path']), case / 'json', args)
    result['json_run'] = run
    result['error'] = error(Path(run['stderr_path']).read_text(errors='replace'))
    result['diagnostic_codes'] = []
    result['render_diagnostic_codes'] = []
    expected = reference(record)
    result['reference_available'] = expected is not None
    if expected is not None and expected.lstrip().startswith(('ERROR:', 'PANIC')):
        result['comparison'] = {'reference_is_error': True}
    if run['harness_stop'] or run['exit_code'] not in (0, 2):
        result['outcome'] = 'stopped' if run['harness_stop'] else 'crashed' if run['exit_code'] < 0 else 'failed'
        return result
    try:
        parsed = json.loads(Path(run['stdout_path']).read_text())
    except ValueError:
        result['outcome'] = 'invalid_json'
        return result
    result['parse_status'] = parsed['status']
    result['diagnostic_codes'] = sorted({d['code'] for d in parsed['diagnostics']})
    result['model_counts'] = count_model(parsed['document'])
    run = run_cli(binary, Path(record['source_path']), case / 'markdown', args)
    result['markdown_run'] = run
    stderr = Path(run['stderr_path']).read_text(errors='replace')
    result['render_diagnostic_codes'] = sorted(set(re.findall(r'^(markdown_\w+):', stderr, re.M)))
    if run['harness_stop'] or run['exit_code'] not in (0, 2):
        result['outcome'] = 'stopped' if run['harness_stop'] else 'crashed' if run['exit_code'] < 0 else 'render_failed'
        result['error'] = error(stderr)
        return result
    actual = Path(run['stdout_path']).read_text()
    result['outcome'] = 'partial' if run['exit_code'] == 2 or parsed['status'] == 'partial' else 'complete'
    result['markdown_bytes'] = len(actual.encode())
    result['empty_output'] = not actual.strip()
    if expected is not None: result['comparison'] = compare(actual, expected)
    return result


def summarize(results):
    grouped = defaultdict(Counter)
    for r in results: grouped[(r['project'], r['group'], r['format'])][r['outcome']] += 1
    return {'cases': len(results), 'outcomes': dict(Counter(r['outcome'] for r in results)),
            'by_group_format': [{'project': p, 'group': g, 'format': f, 'outcomes': dict(c)} for (p,g,f),c in sorted(grouped.items())],
            'diagnostics_by_document': dict(Counter(d for r in results for d in r['diagnostic_codes'])),
            'reference_comparisons': sum('token_recall_proxy' in r.get('comparison', {}) for r in results),
            'normalized_exact_matches': sum(r.get('comparison', {}).get('normalized_exact', False) for r in results)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--anydoc', type=Path, default=ROOT / 'anydoc-main')
    parser.add_argument('--docling', type=Path, default=ROOT / 'docling-main')
    parser.add_argument('--binary', type=Path, default=ROOT / 'target/release/bulkparse')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--timeout', type=float, default=10)
    parser.add_argument('--cpu-seconds', type=int, default=8)
    parser.add_argument('--rss-mib', type=int, default=512)
    parser.add_argument('--output-mib', type=int, default=16)
    args = parser.parse_args()
    if min(args.timeout, args.cpu_seconds, args.rss_mib, args.output_mib) <= 0:
        parser.error('budgets must be positive')
    args.binary = args.binary.resolve()
    manifest = inventory(args.anydoc.resolve(), args.docling.resolve())
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=False)
    artifacts = ROOT / 'target/fixture-evaluations' / output.name
    artifacts.mkdir(parents=True, exist_ok=False)
    metadata = {'created_utc': datetime.now(timezone.utc).isoformat(), 'platform': platform.platform(),
                'python': platform.python_version(), 'binary_sha256': sha(args.binary),
                'rust_source_sha256': source_digest(), 'harness_sha256': sha(Path(__file__)),
                'budgets': vars(args) | {'binary': str(args.binary)},
                'method': 'Two CLI subprocesses; default parser options; no competitor execution. Times include process startup and polling overhead, not performance benchmarks.',
                'memory': 'wait4 reports per-child peak RSS. RLIMIT_AS is enforced on Linux only; the rss-mib option does not impose a memory bound on macOS. CPU, output and wall-time limits apply on both.',
                'license_note': 'Source and reference files stay in their checkouts. Raw converted text stays under ignored target/. Redistribution rights are unreviewed.'}
    (output / 'run.json').write_text(json.dumps(metadata, indent=2, default=str) + '\n')
    (output / 'manifest.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in manifest))
    results = []
    with (output / 'results.jsonl').open('w') as f:
        for i, record in enumerate(manifest, 1):
            result = evaluate(record, args.binary, artifacts, args)
            results.append(result)
            f.write(json.dumps(result) + '\n'); f.flush()
            if i % 10 == 0 or result['outcome'] in {'crashed', 'stopped'}:
                print(f'{i}/{len(manifest)} {record["id"]}: {result["outcome"]}', flush=True)
    summary = summarize(results)
    (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
